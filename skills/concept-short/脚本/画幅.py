"""画幅：横屏为主（1920×1080），竖屏为辅（1080×1920）。片子.json 写 "画幅": "横" | "竖"，不写就是横屏。
尺寸、安全区、字幕字号和默认位置只写在这里一份：render.py 把 LAYOUT 注入页面（window.LAYOUT），检查.py、终检.py、音效.py、审片包.py 也从这里读。
  竖屏沿用 v3（手机实测过）。横屏是 v4 新定的：普通字号 54（《傲慢》720p 下 36px 的等比放大），下方让开平台的进度条（底部 7%），左右各 8%，没有右侧按钮列。"""
import json
from pathlib import Path

LAYOUTS = {
    '竖': {'画幅': '竖', 'W': 1080, 'H': 1920,
           '安全': {'上': .12, '下': .80, '左右': .06, '按钮列': [.88, .45, .80]},   # 按钮列：x 超过 .88、y 在 .45–.80
           '字号': {'普通': [58, 600], '问句': [70, 700], '心里话': [58, 400], '引文': [50, 400]}, '最小字号': 52,
           '字幕': {'x': .5, 'y': .73, '宽': .86}},
    '横': {'画幅': '横', 'W': 1920, 'H': 1080,
           '安全': {'上': .07, '下': .93, '左右': .08, '按钮列': None},
           '字号': {'普通': [54, 600], '问句': [64, 700], '心里话': [54, 400], '引文': [46, 400]}, '最小字号': 46,
           '字幕': {'x': .5, 'y': .85, '宽': .72}},
}


def of_state(state):
    k = (state or {}).get('画幅', '横')
    if k not in LAYOUTS: raise SystemExit(f'片子.json 的 "画幅" 只能是 "横" 或 "竖"，现在是 {k!r}')
    return LAYOUTS[k]


def of_film(film):
    f = Path(film) / '片子.json'
    return of_state(json.loads(f.read_text(encoding='utf-8')) if f.exists() else {})


def of_size(w, h):
    """按视频尺寸认画幅（终检读成片时用）；不是两种标准尺寸之一返回 None"""
    return next((L for L in LAYOUTS.values() if (L['W'], L['H']) == (w, h)), None)
